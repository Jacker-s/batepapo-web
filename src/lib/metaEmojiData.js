export function getMetaEmojiList(category, recents = []) {
  if (category === 'RECENTS') {
    return recents.length ? recents : META_EMOJI_FALLBACK_RECENTS;
  }
  if (category === 'ALL') {
    return [
      ...META_EMOJI_DATA.FACES,
      ...META_EMOJI_DATA.HANDS,
      ...META_EMOJI_DATA.HEARTS,
      ...META_EMOJI_DATA.ANIMALS,
      ...META_EMOJI_DATA.FOOD,
      ...META_EMOJI_DATA.OBJECTS,
      ...META_EMOJI_DATA.SYMBOLS,
      ...META_EMOJI_FALLBACK_RECENTS
    ];
  }
  return META_EMOJI_DATA[category] || META_EMOJI_FALLBACK_RECENTS;
}
